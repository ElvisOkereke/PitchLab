// The tour's chapters, in the order of the real workflow (spec §2). Every title and body is a string literal:
// driver.js renders them with innerHTML, so no step text may ever come from case, prospect, LLM or user data, and
// none may contain < > or & (tests enforce this). Targets are `data-tour` ids; test/tour-anchors.test.ts checks that
// each one exists in exactly one component and that every component anchor is used here.
import type { TourChapterId } from '@bcg/core/dashboard/tour';
import type { TourCtx, TourStep } from './machine';

type CaseTabParam = 'evidence' | 'numbers' | 'competitors' | 'pitch' | 'validate' | 'score';

/** A step on the tour's case (newest real case, else the example), on one tab; null when there is no case at all. */
const onCase = (tab?: CaseTabParam) => (ctx: TourCtx): string | null =>
  ctx.caseSlug ? `/cases/${encodeURIComponent(ctx.caseSlug)}${tab ? `?tab=${tab}` : ''}` : null;

/** Advances when the case page switches to this tab. */
const tabPath = (tab: CaseTabParam) => new RegExp(`[?&]tab=${tab}(&|$)`);

